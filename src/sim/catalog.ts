let seq = 1;

export function createBody(
  catalogId: CatalogId,
  position: [number, number, number],
  extras: Partial<SimBody> = {},
): SimBody {
  const item = CATALOG[catalogId];
  const volume = volumeOf(item.shape, item.size);
  const mass = Math.max(0.004, item.density * volume);
  const anchored =
    extras.anchored ??
    (item.kind === "electromagnet" ||
      item.kind === "tube" ||
      item.kind === "pool");

  return {
    id: extras.id ?? `${catalogId}-${seq++}`,
    kind: item.kind,
    catalogId,
    label: extras.label ?? item.label,
    position,
    rotation: extras.rotation ?? [0, 0, 0],
    size: extras.size ?? item.size,
    shape: item.shape,
    mass: extras.mass ?? mass,
    density: item.density,
    Br: extras.Br ?? item.Br,
    polarity: extras.polarity ?? 1,
    momentAxis: extras.momentAxis ?? item.momentAxis,
    voltage: extras.voltage ?? item.voltage,
    resistance: item.resistance,
    turns: item.turns,
    coreMuR: item.coreMuR,
    powered: extras.powered ?? item.kind === "electromagnet",
    conductivity: item.conductivity,
    chi: item.chi,
    anchored,
    color: item.color,
  };
}

export function volumeOf(shape: CatalogItem["shape"], size: [number, number, number]) {
  const [sx, sy, sz] = size;
  switch (shape) {
    case "sphere":
      return (4 / 3) * Math.PI * Math.pow(sx / 2, 3);
    case "cylinder":
    case "coil":
      return Math.PI * Math.pow(sx / 2, 2) * sy;
    case "tube":
      return Math.PI * (Math.pow(sx / 2, 2) - Math.pow(sx / 2 - 0.004, 2)) * sy;
    case "pool":
      return Math.PI * Math.pow(sx / 2, 2) * sy;
    case "horseshoe":
      return sx * sy * sz * 0.55;
    default:
      return sx * sy * sz;
  }
}

export function characteristicSize(size: [number, number, number]) {
  return Math.max(size[0], size[1], size[2]);
}
